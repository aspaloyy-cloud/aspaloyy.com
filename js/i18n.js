window.setLang = function(lang) {
  var t = window.LANG[lang] || window.LANG.ru;
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.documentElement.lang = lang;
  var sel = document.getElementById('langSelect');
  if (sel) sel.value = lang;
  localStorage.setItem('asp_lang', lang);
  window._currentLang = lang;
};

window._currentLang = localStorage.getItem('asp_lang') || 'ru';
document.addEventListener('DOMContentLoaded', function() {
  var sel = document.getElementById('langSelect');
  if (sel) sel.addEventListener('change', function() { window.setLang(this.value); });
  window.setLang(window._currentLang);
});
